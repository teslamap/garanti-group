import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {initializeTestEnvironment,assertFails,assertSucceeds} from '@firebase/rules-unit-testing';
import {doc,setDoc,getDoc,getDocs,collection,query,limit,updateDoc,writeBatch,serverTimestamp,deleteDoc} from 'firebase/firestore';
import {ref,uploadString,getBytes} from 'firebase/storage';
const projectId='demo-garanti-group';
const env=await initializeTestEnvironment({projectId,firestore:{rules:await readFile('firestore.rules','utf8')},storage:{rules:await readFile('storage.rules','utf8')}});
const owner=env.authenticatedContext('owner'),other=env.authenticatedContext('other'),admin=env.authenticatedContext('admin'),publicUser=env.unauthenticatedContext();
await env.withSecurityRulesDisabled(async c=>{await setDoc(doc(c.firestore(),'admins','admin'),{active:true})});
const orderId='Abcdefghijklmnopqr01';
const item={type:'კარ-ფანჯარა',material:'PVC',width:1000,height:1500,quantity:2,notes:'',photos:['orders/owner/'+orderId+'/0/0']};
const header=()=>({ownerUid:'owner',name:'Test customer',phone:'+995555123456',address:'Tbilisi',notes:'',consent:true,itemCount:1,createdAt:serverTimestamp(),submittedAt:null,status:'მზადდება'});
test('rules validate marketing scope, immutable roles and bounded order reservation',async()=>{
 assert.ok(owner.firestore());
 await assertFails(setDoc(doc(owner.firestore(),'admins','owner'),{active:true}));
 await assertFails(getDocs(collection(publicUser.firestore(),'orders')));
 await assertFails(setDoc(doc(owner.firestore(),'site','content'),{texts:{},links:{},projects:[]}));
 await assertSucceeds(setDoc(doc(admin.firestore(),'site','content'),{texts:{title:'Garanti'},links:{},projects:[]}));
 await assertSucceeds(getDoc(doc(publicUser.firestore(),'site','content')));
 await assertFails(getDocs(collection(publicUser.firestore(),'site')));
 await assertFails(setDoc(doc(owner.firestore(),'orders',orderId),header()));
 const batch=writeBatch(owner.firestore());batch.set(doc(owner.firestore(),'orders',orderId),header());batch.set(doc(owner.firestore(),'orders',orderId,'items','0'),item);batch.set(doc(owner.firestore(),'submissionLimits','owner'),{lastAt:serverTimestamp(),orderId});await assertSucceeds(batch.commit());
 await assertSucceeds(getDoc(doc(owner.firestore(),'orders',orderId)));
 await assertFails(getDoc(doc(other.firestore(),'orders',orderId)));
 await assertFails(getDocs(query(collection(owner.firestore(),'orders'),limit(100))));
 await assertSucceeds(getDocs(query(collection(admin.firestore(),'orders'),limit(100))));
 await assertFails(getDocs(query(collection(admin.firestore(),'orders'),limit(101))));
 await assertFails(updateDoc(doc(owner.firestore(),'orders',orderId),{ownerUid:'other'}));
 await assertFails(updateDoc(doc(owner.firestore(),'orders',orderId,'items','0'),{quantity:0}));
 await assertFails(setDoc(doc(other.firestore(),'orders',orderId,'items','1'),item));
 // A real PNG keeps MIME/type validation separate from file contents.
 const image='iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=';
 const storage=owner.storage();const path='orders/owner/'+orderId+'/0/0';
 await assertSucceeds(uploadString(ref(storage,path),image,'base64',{contentType:'image/png'}));
 await assertFails(getBytes(ref(other.storage(),path)));
 await assertFails(getBytes(ref(publicUser.storage(),path)));
 await assertSucceeds(getBytes(ref(admin.storage(),path)));
 await assertFails(uploadString(ref(storage,'orders/other/'+orderId+'/0/0'),image,'base64',{contentType:'image/png'}));
 await assertFails(uploadString(ref(storage,'orders/owner/'+orderId+'/0/1'),image,'base64',{contentType:'image/svg+xml'}));
 await assertSucceeds(updateDoc(doc(owner.firestore(),'orders',orderId),{status:'ახალი',submittedAt:serverTimestamp()}));
 await assertFails(updateDoc(doc(owner.firestore(),'orders',orderId),{status:'დასრულებული'}));
 await assertFails(updateDoc(doc(admin.firestore(),'orders',orderId),{phone:'new-number'}));
 await assertSucceeds(updateDoc(doc(admin.firestore(),'orders',orderId),{status:'დაკავშირება'}));
 await assertFails(uploadString(ref(storage,path),image,'base64',{contentType:'image/png'}));
 const next='Abcdefghijklmnopqr02';const repeat=writeBatch(owner.firestore());repeat.set(doc(owner.firestore(),'orders',next),header());repeat.set(doc(owner.firestore(),'submissionLimits','owner'),{lastAt:serverTimestamp(),orderId:next});await assertFails(repeat.commit());
 await assertFails(deleteDoc(doc(owner.firestore(),'orders',orderId)));
});
test.after(async()=>{await env.cleanup()});
